//! AOT emitter: turn a [`BuiltPlan`] into a Rust file
//! containing the kernel functions, a `KERNELS` table and a `plan()` builder.
//!
//! This emits **Rust source**, not a binary library. The application
//! `include!`s the file (usually from `build.rs`), and Cargo/rustc compiles the
//! kernels into the application binary; no runtime `rustc` or `.so` is needed.
//! The JIT path (`FrozenRunner::new`) uses the loaded `rustc` cdylibs instead.

use std::fmt::Write as _;
use std::path::Path;

use super::plan::{BuiltPlan, FrozenPlan, Step};

const MATH: &str = r#"// --- autorust frozen plan -----------------------------------------------
// Generated by `autorust::freeze::emit`; do not edit.

#[allow(dead_code, unused_mut, unused_variables, unused_parens, unsafe_op_in_unsafe_fn)]
#[cfg(target_arch = "x86_64")]
#[inline(always)]
pub unsafe fn sqrtf(x: f32) -> f32 {
    core::arch::x86_64::_mm_cvtss_f32(
        core::arch::x86_64::_mm_sqrt_ss(core::arch::x86_64::_mm_set_ss(x)),
    )
}
#[allow(dead_code, unused_mut, unused_variables, unused_parens, unsafe_op_in_unsafe_fn)]
#[cfg(not(target_arch = "x86_64"))]
#[inline(always)]
pub unsafe fn sqrtf(x: f32) -> f32 {
    unsafe extern "C" {
        fn sqrtf(x: f32) -> f32;
    }
    sqrtf(x)
}

#[allow(dead_code, unused_mut, unused_variables, unused_parens, unsafe_op_in_unsafe_fn)]
#[cfg(target_arch = "x86_64")]
#[inline(always)]
pub unsafe fn sqrt(x: f64) -> f64 {
    core::arch::x86_64::_mm_cvtsd_f64(core::arch::x86_64::_mm_sqrt_sd(
        core::arch::x86_64::_mm_setzero_pd(),
        core::arch::x86_64::_mm_set_sd(x),
    ))
}
#[allow(dead_code, unused_mut, unused_variables, unused_parens, unsafe_op_in_unsafe_fn)]
#[cfg(not(target_arch = "x86_64"))]
#[inline(always)]
pub unsafe fn sqrt(x: f64) -> f64 {
    unsafe extern "C" {
        fn sqrt(x: f64) -> f64;
    }
    sqrt(x)
}

#[cfg_attr(unix, link(name = "m"))]
unsafe extern "C" {
    pub fn exp2f(x: f32) -> f32;
    pub fn exp2(x: f64) -> f64;
    pub fn log2f(x: f32) -> f32;
    pub fn log2(x: f64) -> f64;
    pub fn sinf(x: f32) -> f32;
    pub fn sin(x: f64) -> f64;
    pub fn truncf(x: f32) -> f32;
    pub fn trunc(x: f64) -> f64;
}

pub type KernelFn = unsafe extern "C" fn(*const *mut u8, *const i64, *const i64);
"#;

/// Emit the generated Rust source for `built`.
pub fn emit_rust(built: &BuiltPlan) -> String {
    let mut out = String::new();
    out.push_str(MATH);

    for (i, cp) in built.kernels.iter().enumerate() {
        let src = cp.source.clone();
        // `no_mangle` would collide when several kernels share a name; the
        // modules below provide the namespace instead.
        let src: String = src
            .lines()
            .filter(|l| !l.trim().starts_with("#[unsafe(no_mangle)]"))
            .collect::<Vec<_>>()
            .join("\n");
        writeln!(out, "pub mod k{i} {{").unwrap();
        out.push_str("#[allow(unused_imports)]\nuse super::*;\n");
        out.push_str(&src);
        out.push_str("\n}\n");
    }

    out.push_str("pub static KERNELS: &[KernelFn] = &[\n");
    for (i, cp) in built.kernels.iter().enumerate() {
        writeln!(out, "    k{i}::{},", cp.elf.name).unwrap();
    }
    out.push_str("];\n\n");
    out.push_str(&plan_source(&built.plan));
    out
}

fn plan_source(plan: &FrozenPlan) -> String {
    let mut s = String::new();
    s.push_str("pub fn plan() -> autorust::freeze::FrozenPlan {\n");
    s.push_str("    autorust::freeze::FrozenPlan {\n");
    s.push_str("        storages: vec![\n");
    for st in &plan.storages {
        writeln!(
            s,
            "            autorust::freeze::StorageSpec {{ nbytes: {}, external: {} }},",
            st.nbytes, st.external
        )
        .unwrap();
    }
    s.push_str("        ],\n        views: vec![\n");
    for v in &plan.views {
        writeln!(
            s,
            "            autorust::freeze::ViewSpec {{ storage: {}, offset: {}, nbytes: {}, dtype: autorust::dtype::DTypeId({}) }},",
            v.storage, v.offset, v.nbytes, v.dtype.0
        )
        .unwrap();
    }
    s.push_str("        ],\n        steps: vec![\n");
    for step in &plan.steps {
        match step {
            Step::Gemm { gemm, bufs } => {
                let bufs: Vec<String> = bufs.iter().map(usize::to_string).collect();
                writeln!(
                    s,
                    "            autorust::freeze::Step::Gemm {{ gemm: Box::new({}), bufs: vec![{}] }},",
                    gemm.to_rust_literal(),
                    bufs.join(", ")
                )
                .unwrap();
            }
            Step::Copy { dst, src } => {
                writeln!(
                    s,
                    "            autorust::freeze::Step::Copy {{ dst: {dst}, src: {src} }},"
                )
                .unwrap();
            }
            Step::Kernel {
                kernel,
                bufs,
                vals,
                global,
            } => {
                let bufs: Vec<String> = bufs.iter().map(usize::to_string).collect();
                let vals: Vec<String> = vals.iter().map(i64::to_string).collect();
                writeln!(
                    s,
                    "            autorust::freeze::Step::Kernel {{ kernel: {kernel}, bufs: vec![{}], vals: vec![{}], global: [{}, {}, {}] }},",
                    bufs.join(", "),
                    vals.join(", "),
                    global[0],
                    global[1],
                    global[2]
                )
                .unwrap();
            }
        }
    }
    s.push_str("        ],\n");
    let ids = |v: &[usize]| {
        v.iter()
            .map(usize::to_string)
            .collect::<Vec<_>>()
            .join(", ")
    };
    writeln!(s, "        inputs: vec![{}],", ids(&plan.inputs)).unwrap();
    writeln!(s, "        weights: vec![{}],", ids(&plan.weights)).unwrap();
    writeln!(s, "        outputs: vec![{}],", ids(&plan.outputs)).unwrap();
    s.push_str("        output_shapes: vec![\n");
    for shape in &plan.output_shapes {
        let shape: Vec<String> = shape.iter().map(i64::to_string).collect();
        writeln!(s, "            vec![{}],", shape.join(", ")).unwrap();
    }
    s.push_str("        ],\n");
    s.push_str("        kernel_names: vec![\n");
    for name in &plan.kernel_names {
        writeln!(s, "            {:?}.to_string(),", name).unwrap();
    }
    s.push_str("        ],\n");
    s.push_str("    }\n}\n");
    s
}

/// Write the emitted source to `path`.
pub fn emit_to(built: &BuiltPlan, path: impl AsRef<Path>) -> std::io::Result<()> {
    std::fs::write(path, emit_rust(built))
}
