#!/usr/bin/env python3
"""Render bench/results/*.json as markdown tables.

Writes bench/results/summary.md and prints it. Numbers are medians from
run.py; see bench/README.md for the methodology and caveats.

Single-number workloads render one table per model with `ms/step` and a
throughput column; microbenches (`gemm`, `memops`, `optim`, `freeze`) carry a
`cases` array and render one row per case, so the per-shape numbers stay
visible instead of being averaged away.
"""

import json
import pathlib

BENCH = pathlib.Path(__file__).resolve().parent
RESULTS = BENCH / "results"

# (workload, title, unit) — `unit` labels the throughput column.
WORKLOADS = [
    ("mnist_train", "MNIST CNN training", "img"),
    ("vit_infer", "ViT-B/16 inference", "img"),
    ("vit_train", "ViT-B/16 training step (f32)", "img"),
    ("vit_infer_bf16", "ViT-B/16 inference (bf16)", "img"),
    ("resnet18_infer", "ResNet-18 inference (224²)", "img"),
    ("resnet18_train", "ResNet-18 training step (224²)", "img"),
    ("resnet50_infer", "ResNet-50 inference (224²)", "img"),
    ("mobilenet_infer", "MobileNetV2 inference (224²)", "img"),
    ("unet_infer", "UNet inference (64²)", "img"),
    ("llm_prefill", "LLM prefill (512 tokens)", "token"),
    ("llm_decode", "LLM decode (1 token, 512-token KV cache)", "token"),
    ("onnx_mnist", "MNIST inference via the ONNX runner (bs 32)", "img"),
    ("onnx_resnet", "ResNet-18 (width 0.25) via the ONNX runner (bs 8)", "img"),
]

# Multi-case workloads: (workload, title, metric key or None).
MULTI = [
    ("gemm", "GEMM sweep (f32 / bf16)", "tflops"),
    ("memops", "Memory-bound ops (16M f32 elements)", "gbs"),
    ("optim", "AdamW step (~100M parameters)", "gbs"),
    ("freeze", "Frozen CPU plan vs JIT replay (small ViT)", None),
]


def load():
    out = []
    for p in sorted(RESULTS.glob("*.json")):
        out.append(json.loads(p.read_text()))
    return out


def norm_device(d):
    """Map the CPU backends onto the same table device label."""
    return "CPU" if d in ("RUST", "RAYON", "CC", "CLANG") else d


def fmt_ms(x):
    if x >= 1000:
        return f"{x / 1000:.2f} s"
    return f"{x:.2f} ms"


def main():
    rows = load()
    lines = ["# Benchmark summary", ""]
    lines.append(
        "Generated by `bench/report.py` from the raw JSON in this directory. "
        "Median of the timed steps after warmup; see `bench/README.md`."
    )

    for workload, title, unit in WORKLOADS:
        subset = [r for r in rows if r.get("workload") == workload]
        if not subset:
            continue
        lines += ["", f"## {title}", ""]
        lines += [
            f"| run | device | batch | median | {unit}/s |",
            "|---|---|---:|---:|---:|",
        ]
        for r in sorted(subset, key=lambda r: (norm_device(r["device"]), r.get("batch", 0), r["ms_median"])):
            ms = r["ms_median"]
            rate = r["batch"] * 1e3 / ms if ms else float("nan")
            name = r.get("name", r["framework"])
            lines.append(
                f"| {name} | {norm_device(r['device'])} | {r['batch']} | {fmt_ms(ms)} | {rate:.1f} |"
            )

    for workload, title, metric in MULTI:
        subset = [r for r in rows if r.get("workload") == workload]
        subset = [r for r in subset if r.get("cases")]
        if not subset:
            continue
        lines += ["", f"## {title}", ""]
        # {(case, device): {framework: (ms, value)}}
        table = {}
        for r in subset:
            fw = r["framework"]
            for c in r["cases"]:
                key = (c["case"], norm_device(r["device"]))
                table.setdefault(key, {})[fw] = (c["ms"], c.get(metric) if metric else None)
        frameworks = [f for f in ("autorust", "candle", "torch", "tinygrad")
                      if any(f in v for v in table.values())]
        head = "| case | device | " + " | ".join(frameworks) + " |"
        lines += [head, "|---|---|" + "---:|" * len(frameworks)]
        for (case, device), vals in table.items():
            cells = []
            for fw in frameworks:
                if fw not in vals:
                    cells.append("—")
                    continue
                ms, val = vals[fw]
                if metric:
                    cells.append(f"{ms:.2f} ms ({val:.1f} {metric})")
                else:
                    cells.append(f"{ms:.2f} ms")
            lines.append(f"| {case} | {device} | " + " | ".join(cells) + " |")

    text = "\n".join(lines) + "\n"
    (RESULTS / "summary.md").write_text(text)
    print(text)


if __name__ == "__main__":
    main()
