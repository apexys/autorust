#!/usr/bin/env python3
"""Render bench/results/*.json as markdown tables.

Writes bench/results/summary.md and prints it. Numbers are medians from
run.py; see bench/README.md for the methodology and caveats.
"""

import json
import pathlib

BENCH = pathlib.Path(__file__).resolve().parent
RESULTS = BENCH / "results"

WORKLOADS = [
    ("mnist_train", "MNIST CNN training (batch 512)"),
    ("vit_infer", "ViT-B/16 inference"),
    ("vit_train", "ViT-B/16 training step (batch 1, f32)"),
]


def load():
    out = []
    for p in sorted(RESULTS.glob("*.json")):
        out.append(json.loads(p.read_text()))
    return out


def fmt_ms(x):
    if x >= 1000:
        return f"{x / 1000:.2f} s"
    return f"{x:.2f} ms"


def main():
    rows = load()
    lines = ["# Benchmark summary", ""]
    lines.append(
        "Generated by `bench/report.py` from the raw JSON in this directory. "
        "Median of the timed steps after warmup; see `bench/README.md`."
    )
    for workload, title in WORKLOADS:
        subset = [r for r in rows if r.get("workload") == workload]
        if not subset:
            continue
        lines += ["", f"## {title}", ""]
        if workload == "vit_infer":
            lines += ["| run | device | batch | median | ms/image | images/s |", "|---|---|---:|---:|---:|---:|"]
        else:
            lines += ["| run | device | batch | median | images/s | s/epoch |", "|---|---|---:|---:|---:|---:|"]
        for r in sorted(subset, key=lambda r: (r["device"], r["ms_median"])):
            images = r["batch"] / (r["ms_median"] / 1e3)
            image_ms = r["ms_median"] / r["batch"]
            name = r.get("name", r["framework"])
            if workload == "vit_infer":
                lines.append(
                    f"| {name} | {r['device']} | {r['batch']} | "
                    f"{fmt_ms(r['ms_median'])} | {image_ms:.2f} ms | {images:.1f} |"
                )
            else:
                epoch = (
                    f"{r['ms_median'] / 1e3 * (60000 / r['batch']):.1f} s"
                    if workload == "mnist_train" else "—"
                )
                lines.append(
                    f"| {name} | {r['device']} | {r['batch']} | "
                    f"{fmt_ms(r['ms_median'])} | {images:.1f} | {epoch} |"
                )
        lines += ["", "Notes:", ""]
        notes = sorted({r["notes"] for r in subset if r.get("notes")})
        for n in notes:
            lines.append(f"- {n}")
        if not notes:
            lines.append("- —")
    text = "\n".join(lines) + "\n"
    (RESULTS / "summary.md").write_text(text)
    print(text)


if __name__ == "__main__":
    main()
