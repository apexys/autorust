"""Generate tests/tensor_golden.rs: movement/op primitives (cat, tril, triu,
repeat_interleave, gather, clip, lerp) vs tinygrad. Run from autorust/:

  ../tinygrad/.venv/bin/python py/dump_tensor_golden.py
"""
import sys
sys.path.insert(0, "../tinygrad")

from tinygrad import Tensor
from tinygrad.dtype import dtypes

CASES = []


def add(name, kind, out, a=None, b=None, idx=None, params=()):
    CASES.append((name, kind, a, b, idx, list(params), out))


def seq(shape, scale=0.3, off=-0.4):
    n = 1
    for s in shape:
        n *= s
    return Tensor.arange(n).reshape(shape).float() * scale + off


# cat: equal-size fast path and unequal (general) path
a = seq((2, 3)); b = seq((2, 3), 0.5, 1.0)
add("cat_eq_dim1", "cat", a.cat(b, dim=1), a=a, b=b, params=[1])
a = seq((2, 1)); b = seq((2, 4), 0.5, 1.0)
add("cat_uneq_dim1", "cat", a.cat(b, dim=1), a=a, b=b, params=[1])
a = seq((2, 3)); b = seq((4, 3), 0.5, 1.0)
add("cat_dim0", "cat", a.cat(b, dim=0), a=a, b=b, params=[0])

# tril / triu
a = seq((3, 4))
add("tril", "tril", a.tril(), a=a, params=[0])
add("tril_diag1", "tril", a.tril(1), a=a, params=[1])
add("triu", "triu", a.triu(), a=a, params=[0])
add("triu_diagneg1", "triu", a.triu(-1), a=a, params=[-1])

# repeat_interleave (with dim, and flattening None)
a = seq((2, 3))
add("repeat_dim1", "repeat_interleave", a.repeat_interleave(2, dim=1), a=a, params=[2, 1])
add("repeat_dim0", "repeat_interleave", a.repeat_interleave(3, dim=0), a=a, params=[3, 0])
add("repeat_none", "repeat_interleave", a.repeat_interleave(2), a=a, params=[2, -1])

# gather
a = seq((2, 4))
idx = Tensor([[0, 1, 0], [3, 2, 3]], dtype=dtypes.int32)
add("gather_dim1", "gather", a.gather(1, idx), a=a, idx=idx, params=[1])

# clip / lerp
a = seq((5,), 1.0, -1.6)
add("clip", "clip", a.clip(-1.0, 1.0), a=a, params=[-1.0, 1.0])
add("clip_min", "clip", a.clip(min_=0.0), a=a, params=[0.0, float("nan")])
a = seq((4,)); b = seq((4,), 0.5, 1.0)
add("lerp", "lerp", a.lerp(b, 0.25), a=a, b=b, params=[0.25])


# interpolate: linear (bilinear), nearest, nearest-exact
a = seq((1, 1, 2, 2))
add("interp_linear_up", "interpolate", a.interpolate((4, 4), mode="linear"), a=a, params=[0, 0, 4, 4])
a = seq((1, 1, 4, 4))
add("interp_linear_down", "interpolate", a.interpolate((2, 2), mode="linear"), a=a, params=[0, 0, 2, 2])
a = seq((1, 1, 2, 2))
add("interp_linear_align", "interpolate", a.interpolate((4, 4), mode="linear", align_corners=True), a=a, params=[0, 1, 4, 4])
a = seq((1, 1, 3, 3))
add("interp_nearest", "interpolate", a.interpolate((5, 5), mode="nearest"), a=a, params=[1, 0, 5, 5])
a = seq((1, 1, 3, 3))
add("interp_nearest_exact", "interpolate", a.interpolate((5, 5), mode="nearest-exact"), a=a, params=[2, 0, 5, 5])
a = seq((2, 1, 2, 3))
add("interp_bilinear_bs", "interpolate", a.interpolate((4, 6), mode="linear"), a=a, params=[0, 0, 4, 6])

def ishape(t):
    return ", ".join(str(int(s)) for s in t.shape)


def sf(vals):
    return ", ".join("f64::NAN" if v != v else repr(float(v)) for v in vals)


def s(vals):
    return ", ".join(repr(float(v)) for v in vals)


def sidx(vals):
    return ", ".join(str(int(v)) for v in vals)


def flat(t):
    return [float(v) for v in t.flatten().tolist()]


L = []
L.append("// GENERATED by py/dump_tensor_golden.py - movement/op primitives vs tinygrad.")
L.append("// Regenerate with `../tinygrad/.venv/bin/python py/dump_tensor_golden.py`.")
L.append("#![allow(clippy::excessive_precision)]")
L.append("")
L.append("pub struct TensorOpGolden {")
L.append("    pub name: &'static str, pub kind: &'static str,")
L.append("    pub a_shape: &'static [usize], pub a: &'static [f32],")
L.append("    pub b_shape: &'static [usize], pub b: &'static [f32],")
L.append("    pub idx_shape: &'static [usize], pub idx: &'static [i32],")
L.append("    pub params: &'static [f64],")
L.append("    pub out_shape: &'static [usize], pub out: &'static [f32],")
L.append("}")
L.append("")
L.append("pub static TENSOR_OPS: &[TensorOpGolden] = &[")
for name, kind, a, b, idx, params, out in CASES:
    ash = f"&[{ishape(a)}]" if a is not None else "&[]"
    av = f"&[{s(flat(a))}]" if a is not None else "&[]"
    bsh = f"&[{ishape(b)}]" if b is not None else "&[]"
    bv = f"&[{s(flat(b))}]" if b is not None else "&[]"
    ish = f"&[{ishape(idx)}]" if idx is not None else "&[]"
    iv = f"&[{sidx(idx.flatten().tolist())}]" if idx is not None else "&[]"
    L.append(
        f'    TensorOpGolden {{ name: "{name}", kind: "{kind}", '
        f"a_shape: {ash}, a: {av}, b_shape: {bsh}, b: {bv}, "
        f"idx_shape: {ish}, idx: {iv}, params: &[{sf(params)}], "
        f"out_shape: &[{ishape(out)}], out: &[{s(flat(out))}] }},"
    )
L.append("];")
L.append("")
open("tests/tensor_golden.rs", "w").write("\n".join(L))
print("wrote tests/tensor_golden.rs")
