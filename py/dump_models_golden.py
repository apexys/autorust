"""Generate tests/models_golden.rs: TransformerBlock + ViT forward vs tinygrad.
Uses seed parity (the port's Threefry RNG matches tinygrad) so the same seed
reproduces the oracle's random init. Run from autorust/:

  ../tinygrad/.venv/bin/python py/dump_models_golden.py
"""
import sys
sys.path.insert(0, "../tinygrad")

from tinygrad import Tensor, Context
from extra.models.transformer import TransformerBlock


def seq(shape, scale=0.3, off=-0.4):
    n = 1
    for s in shape:
        n *= s
    return Tensor.arange(n).reshape(shape).float() * scale + off


def flat(t):
    return [float(v) for v in t.flatten().tolist()]


def shp(t):
    return ", ".join(str(int(s)) for s in t.shape)


def s(vals):
    return ", ".join(repr(v) for v in vals)


# TransformerBlock: rich deterministic input.
BLOCK_SEED = 1234
Tensor.manual_seed(BLOCK_SEED)
blk = TransformerBlock(embed_dim=8, num_heads=2, ff_dim=16, prenorm=True, act=lambda x: x.gelu())
bx = seq((2, 3, 8))
with Context(TRAINING=0):
    bout = blk(bx)


def make_vit(layers, embed_dim, num_heads, in_channels=3, patch=16, img=224, classes=1000):
    # mirrors extra/models/vit.py without importing it (numpy is unavailable)
    npatch = (img // patch) ** 2
    class V: pass
    v = V()
    v.embedding = (Tensor.uniform(embed_dim, in_channels, patch, patch), Tensor.zeros(embed_dim))
    v.cls = Tensor.ones(1, 1, embed_dim)
    v.pos_embedding = Tensor.ones(1, npatch + 1, embed_dim)
    v.tbs = [TransformerBlock(embed_dim=embed_dim, num_heads=num_heads, ff_dim=embed_dim * 4,
                              prenorm=True, act=lambda x: x.gelu()) for _ in range(layers)]
    v.encoder_norm = (Tensor.uniform(embed_dim), Tensor.zeros(embed_dim))
    v.head = (Tensor.uniform(embed_dim, classes), Tensor.zeros(classes))

    def forward(x):
        ce = v.cls.add(Tensor.zeros(x.shape[0], 1, 1))
        pe = x.conv2d(*v.embedding, stride=patch)
        pe = pe.reshape(pe.shape[0], pe.shape[1], -1).permute(0, 2, 1)
        x = ce.cat(pe, dim=1)
        x = x.add(v.pos_embedding)
        for tb in v.tbs:
            x = tb(x)
        x = x.layernorm().linear(*v.encoder_norm)
        return x[:, 0].linear(*v.head)
    v.forward = forward
    return v

# ViT: tinygrad defaults (3-channel 224, patch 16, 1000 classes); compact
# arange-pattern input so we need not emit 150k literals.
VIT_SEED = 4321
Tensor.manual_seed(VIT_SEED)
vit = make_vit(1, 8, 2)
VN = 1 * 3 * 224 * 224
VSCALE, VOFF = 1e-6, 0.5
vx = (Tensor.arange(VN).float() * VSCALE + VOFF).reshape(1, 3, 224, 224)
with Context(TRAINING=0):
    vout = vit.forward(vx)


L = []
L.append("// GENERATED by py/dump_models_golden.py - TransformerBlock + ViT vs tinygrad.")
L.append("// Regenerate with `../tinygrad/.venv/bin/python py/dump_models_golden.py`.")
L.append("#![allow(clippy::excessive_precision)]")
L.append("")
L.append("pub struct BlockGolden {")
L.append("    pub name: &'static str, pub seed: i64,")
L.append("    pub embed_dim: i64, pub num_heads: i64, pub ff_dim: i64, pub prenorm: bool,")
L.append("    pub x_shape: &'static [usize], pub x: &'static [f32],")
L.append("    pub out_shape: &'static [usize], pub out: &'static [f32],")
L.append("}")
L.append("")
L.append("pub static BLOCK_GOLDEN: &[BlockGolden] = &[")
L.append(
    f'    BlockGolden {{ name: "block", seed: {BLOCK_SEED}, embed_dim: 8, num_heads: 2, ff_dim: 16, prenorm: true, '
    f"x_shape: &[{shp(bx)}], x: &[{s(flat(bx))}], out_shape: &[{shp(bout)}], out: &[{s(flat(bout))}] }},"
)
L.append("];")
L.append("")

L.append("pub struct VitGolden {")
L.append("    pub name: &'static str, pub seed: i64,")
L.append("    pub layers: i64, pub embed_dim: i64, pub num_heads: i64, pub num: i64,")
L.append("    pub x_shape: &'static [usize], pub x_scale: f64, pub x_off: f64,")
L.append("    pub out_shape: &'static [usize], pub out: &'static [f32],")
L.append("}")
L.append("")
L.append("pub static VIT_GOLDEN: &[VitGolden] = &[")
L.append(
    f'    VitGolden {{ name: "vit_tiny", seed: {VIT_SEED}, layers: 1, embed_dim: 8, num_heads: 2, num: {VN}, '
    f"x_shape: &[{shp(vx)}], x_scale: {VSCALE!r}, x_off: {VOFF!r}, out_shape: &[{shp(vout)}], out: &[{s(flat(vout))}] }},"
)
L.append("];")
L.append("")
open("tests/models_golden.rs", "w").write("\n".join(L))
print("wrote tests/models_golden.rs")
