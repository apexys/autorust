"""Generate tests/optim_golden.rs — one-step (and N-step) optimizer numerics.

For each optimizer we build a fresh 3-element parameter with an explicit
gradient, run `steps` optimizer steps in tinygrad (TRAINING context), and emit
the resulting parameter values. The Rust test rebuilds the same parameter,
attaches the same gradient via `UOpCtx::set_grad`, runs the same number of
steps, and compares. Running more than one step pins optimizer-state
persistence (momentum / Adam moments).

Run from autorust/:  ../tinygrad/.venv/bin/python py/dump_optim_golden.py
"""
import sys
sys.path.insert(0, "../tinygrad")

from tinygrad import Tensor
from tinygrad.dtype import dtypes
from tinygrad.helpers import Context, TRAINING
from tinygrad.nn import optim

INIT = [1.0, -2.0, 3.0, 0.5]
GRAD = [0.1, 0.2, -0.3, 0.4]
LR = 0.1


def run(kind, steps, **kw):
    p = Tensor(INIT, dtype=dtypes.float32).is_param_(True)
    p.grad = Tensor(GRAD, dtype=dtypes.float32)
    with Context(TRAINING=1):
        if kind == "SGD":
            o = optim.SGD([p], lr=LR, **kw)
        elif kind == "LARS":
            o = optim.LARS([p], lr=LR, **kw)
        elif kind == "Adam":
            o = optim.Adam([p], lr=LR, **kw)
        elif kind == "AdamW":
            o = optim.AdamW([p], lr=LR, **kw)
        else:
            raise ValueError(kind)
        for _ in range(steps):
            o.step()
    return [float(v) for v in p.tolist()]


# name -> expected-after-N-steps
CASES = [
    ("sgd_1step", "SGD", 1, {}),
    ("sgd_3step", "SGD", 3, {}),
    ("lars_1step", "LARS", 1, {}),
    ("lars_3step", "LARS", 3, {}),
    ("adam_1step", "Adam", 1, {}),
    ("adam_3step", "Adam", 3, {}),
    ("adamw_3step", "AdamW", 3, {}),
]


def emit():
    lines = []
    lines.append("// GENERATED by py/dump_optim_golden.py — optimizer numerics vs tinygrad.")
    lines.append("// Regenerate with `../tinygrad/.venv/bin/python py/dump_optim_golden.py`.")
    lines.append("#![allow(clippy::excessive_precision)]")
    lines.append("")
    lines.append("pub struct OptimGolden {")
    lines.append("    pub name: &'static str,")
    lines.append("    pub init: &'static [f32],")
    lines.append("    pub grad: &'static [f32],")
    lines.append("    pub lr: f32,")
    lines.append("    pub steps: usize,")
    lines.append("    pub expected: &'static [f32],")
    lines.append("}")
    lines.append("")
    entries = []
    for name, kind, steps, kw in CASES:
        vals = run(kind, steps, **kw)
        init_s = ", ".join(repr(float(v)) for v in INIT)
        grad_s = ", ".join(repr(float(v)) for v in GRAD)
        exp_s = ", ".join(repr(float(v)) for v in vals)
        entries.append(
            f'    OptimGolden {{ name: "{name}", init: &[{init_s}], grad: &[{grad_s}], '
            f"lr: {LR!r}, steps: {steps}, expected: &[{exp_s}] }},"
        )
    lines.append("pub static OPTIM_GOLDEN: &[OptimGolden] = &[")
    lines.extend(entries)
    lines.append("];")
    lines.append("")
    return "\n".join(lines)


if __name__ == "__main__":
    with open("tests/optim_golden.rs", "w") as f:
        f.write(emit() + "\n")
    print("wrote tests/optim_golden.rs")