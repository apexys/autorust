"""Generate tests/dropout_golden.rs — `Tensor.dropout` numerics vs tinygrad
(`mixin/rand.py:274-296`). Proves the Threefry RNG + masked scaling match the
oracle exactly for a fixed seed. Run from autorust/:

  ../tinygrad/.venv/bin/python py/dump_dropout_golden.py
"""
import sys
sys.path.insert(0, "../tinygrad")

from tinygrad import Tensor, Context
from tinygrad.dtype import dtypes

CASES = []


def dadd(name, shape, p, seed):
    Tensor.manual_seed(seed)
    with Context(TRAINING=1):
        y = Tensor.ones(shape, dtype=dtypes.float32).dropout(p)
    CASES.append((name, shape, p, seed, [float(v) for v in y.flatten().tolist()]))


dadd("d50_20", (20,), 0.5, 1234)
dadd("d25_2x5", (2, 5), 0.25, 7)
dadd("d10_4x4", (4, 4), 0.1, 99)
dadd("d100_8", (8,), 1.0, 3)
dadd("d0_8", (8,), 0.0, 3)


def ishape(shape):
    return ", ".join(str(s) for s in shape)


def s(vals):
    return ", ".join(repr(v) for v in vals)


L = []
L.append("// GENERATED by py/dump_dropout_golden.py - dropout numerics vs tinygrad.")
L.append("// Regenerate with `../tinygrad/.venv/bin/python py/dump_dropout_golden.py`.")
L.append("#![allow(clippy::excessive_precision)]")
L.append("")
L.append("pub struct DropoutGolden {")
L.append("    pub name: &'static str, pub shape: &'static [usize], pub p: f64, pub seed: i64,")
L.append("    pub out: &'static [f32],")
L.append("}")
L.append("")
L.append("pub static DROPOUT_GOLDEN: &[DropoutGolden] = &[")
for name, shape, p, seed, out in CASES:
    L.append(
        f'    DropoutGolden {{ name: "{name}", shape: &[{ishape(shape)}], p: {p!r}, seed: {seed}, '
        f"out: &[{s(out)}] }},"
    )
L.append("];")
L.append("")

open("tests/dropout_golden.rs", "w").write("\n".join(L))
print("wrote tests/dropout_golden.rs")
